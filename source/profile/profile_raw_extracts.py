"""Profile the raw GSS extracts BEFORE any pipeline code exists.

This script is deliberately standard-library only and independent of the
loader and the dbt project.  It reads the raw JSON exactly as delivered by
the GSS Data Explorer, computes the figures quoted in docs/data_profile.md
and writes them as Markdown tables to docs/data_profile_tables.md so the
profile can be regenerated and audited.

Usage:
    python3 source/profile/profile_raw_extracts.py [--raw-dir source/data/raw] [--out docs/data_profile_tables.md]
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, OrderedDict
from pathlib import Path

# The Explorer renders a reserved (missing-data) code as ".<letter>:  <text>".
# A genuine answer never starts with a dot followed by a letter and a colon.
RESERVED_RE = re.compile(r"^\.[a-z]:\s")

# Reserved-code families observed in these extracts, mapped to the four
# categories the brief requires us to keep apart (plus the ones that never occur).
RESERVED_FAMILY = OrderedDict(
    [
        (".i", "inapplicable"),  # -100  did not apply (skip pattern / wrong ballot)
        (".y", "not_in_year"),  # -70   variable not fielded in that survey year
        (".d", "dont_know"),  # -98   do not know / cannot choose
        (".n", "no_answer"),  # -99   refused / no answer
        (".s", "skipped_web"),  # -97   skipped on web (2021 self-administered mode)
        (".u", "uncodable"),  # -95   uncodable
        (".r", "refused"),  # -90
        (".x", "not_in_release"),  # -80
        (".m", "dk_na_iap"),  # -40
    ]
)

CUTS = OrderedDict(
    [
        ("cut_a_2016_2018", "post_processing_output.json"),
        ("cut_b_2018_2021", "post_processing_output.json"),
    ]
)


def load_cut(path: Path) -> list[dict]:
    """Return the extract as a list of row dicts (the file is column-oriented)."""
    doc = json.loads(path.read_text())
    cols = doc["data"]
    n = len(next(iter(cols.values())))
    return [{k: cols[k][i] for k in cols} for i in range(n)]


def classify(value) -> str:
    if value is None:
        return "absent"
    s = str(value)
    if RESERVED_RE.match(s):
        return RESERVED_FAMILY.get(s[:2], "other_reserved")
    return "valid"


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", default="source/data/raw")
    ap.add_argument("--out", default="docs/data_profile_tables.md")
    args = ap.parse_args()
    raw = Path(args.raw_dir)

    cuts = {name: load_cut(raw / name / fname) for name, fname in CUTS.items()}
    sections: list[str] = ["# Data profile tables (generated)\n",
                           "Generated by `source/profile/profile_raw_extracts.py` from the raw JSON. Do not edit by hand.\n"]

    # 1. Record counts per cut and per year ---------------------------------
    rows = []
    for name, data in cuts.items():
        by_year = Counter(r["year"] for r in data)
        for y in sorted(by_year):
            rows.append([name, y, by_year[y]])
        rows.append([name, "**total**", f"**{len(data)}**"])
    sections.append("## 1. Record counts per cut and survey year\n\n" + md_table(["cut", "year", "records"], rows))

    # 2. Overlap audit --------------------------------------------------------
    keys = {name: {(r["year"], r["id_"]) for r in data} for name, data in cuts.items()}
    a, b = keys["cut_a_2016_2018"], keys["cut_b_2018_2021"]
    both = a & b
    dup = {name: len(data) - len(k) for (name, data), k in zip(cuts.items(), keys.values())}
    rows = [
        ["respondents in cut A", len(a)],
        ["respondents in cut B", len(b)],
        ["in both cuts", len(both)],
        ["distinct overall", len(a | b)],
        ["overlap as share of cut A", f"{len(both) / len(a):.1%}"],
        ["overlap as share of cut B", f"{len(both) / len(b):.1%}"],
        ["duplicate (year, id_) keys inside cut A", dup["cut_a_2016_2018"]],
        ["duplicate (year, id_) keys inside cut B", dup["cut_b_2018_2021"]],
    ]
    sections.append("## 2. Overlap audit on (year, id_)\n\n" + md_table(["measure", "value"], rows))

    # 3. Are overlapping rows identical? ------------------------------------
    ia = {(r["year"], r["id_"]): r for r in cuts["cut_a_2016_2018"] if r["year"] == "2018"}
    ib = {(r["year"], r["id_"]): r for r in cuts["cut_b_2018_2021"] if r["year"] == "2018"}
    common_cols = [c for c in cuts["cut_a_2016_2018"][0] if c in cuts["cut_b_2018_2021"][0]]
    differing = Counter()
    for k, ra in ia.items():
        rb = ib[k]
        for c in common_cols:
            if ra[c] != rb[c]:
                differing[c] += 1
    sections.append(
        "## 3. Consistency of the 2018 overlap across cuts\n\n"
        + (f"All {len(ia)} overlapping 2018 rows are identical on all {len(common_cols)} shared columns."
           if not differing else md_table(["column", "rows differing"], sorted(differing.items())))
    )

    # 4. Column inventory and schema differences ------------------------------
    cols_a = list(cuts["cut_a_2016_2018"][0].keys())
    cols_b = list(cuts["cut_b_2018_2021"][0].keys())
    only_a = [c for c in cols_a if c not in cols_b]
    only_b = [c for c in cols_b if c not in cols_a]
    types = {}
    for name, data in cuts.items():
        for c in data[0]:
            types.setdefault(c, set()).update(type(r[c]).__name__ for r in data)
    rows = [[c, "yes" if c in cols_a else "no", "yes" if c in cols_b else "no", ", ".join(sorted(types[c]))]
            for c in cols_a + only_b]
    sections.append(
        "## 4. Column inventory\n\n"
        f"Columns only in cut A: {only_a or 'none'}. Columns only in cut B: {only_b or 'none'}.\n\n"
        + md_table(["column", "in cut A", "in cut B", "JSON value types"], rows)
    )

    # 5. Missing share per variable per year (deduplicated respondents) -------
    merged: dict = {}
    for data in cuts.values():
        for r in data:
            merged[(r["year"], r["id_"])] = r  # identical rows, so order is irrelevant
    years = sorted({k[0] for k in merged})
    variables = [c for c in cols_a + only_b if c not in ("year", "id_")]
    fam_cols = list(RESERVED_FAMILY.values())
    detail_rows, summary_rows = [], []
    for v in variables:
        summary = [v]
        for y in years:
            cnt = Counter()
            n = 0
            for k, r in merged.items():
                if k[0] != y:
                    continue
                n += 1
                cnt[classify(r.get(v))] += 1
            missing = n - cnt["valid"]
            dominant = max((f for f in cnt if f != "valid"), key=lambda f: cnt[f], default="-")
            summary.append(f"{missing / n:.1%}" + (f" ({dominant})" if missing else ""))
            detail_rows.append([v, y, n, cnt["valid"], f"{missing / n:.1%}"]
                               + [cnt[f] for f in fam_cols] + [cnt["absent"]])
        summary_rows.append(summary)
    sections.append(
        "## 5. Share of values that are NOT genuine answers, per variable and year\n\n"
        "Computed over distinct respondents (2018 counted once). The dominant reserved-code family is in brackets.\n\n"
        + md_table(["variable"] + years, summary_rows)
    )
    sections.append(
        "## 6. Reserved-code breakdown per variable and year\n\n"
        "`absent` = column not present in the extract that covers that year.\n\n"
        + md_table(["variable", "year", "n", "valid", "missing %"] + fam_cols + ["absent"], detail_rows)
    )

    # 7. Reserved labels actually observed ------------------------------------
    observed = Counter()
    for r in merged.values():
        for v in variables:
            s = r.get(v)
            if s is not None and RESERVED_RE.match(str(s)):
                observed[str(s)] += 1
    sections.append(
        "## 7. Reserved-code labels observed in the data\n\n"
        + md_table(["label as exported", "occurrences"], sorted(observed.items(), key=lambda kv: -kv[1]))
    )

    # 8. id_ ranges per year --------------------------------------------------
    rows = []
    for y in years:
        ids = [k[1] for k in merged if k[0] == y]
        rows.append([y, min(ids), max(ids), len(ids), "yes" if max(ids) == len(ids) else "no (gaps)"])
    sections.append("## 8. Respondent id_ ranges per year\n\n" + md_table(["year", "min id_", "max id_", "rows", "contiguous"], rows))

    # 9. Code-list sizes from the embedded metadata ----------------------------
    doc_b = json.loads((raw / "cut_b_2018_2021" / "post_processing_output.json").read_text())
    rows = []
    for entry in doc_b["codes"].values():
        labels = entry["CodeLabel"]
        substantive = [c for c in labels if int(c) >= 0]
        reserved = [c for c in labels if int(c) < 0]
        rows.append([entry["variable_name"], len(substantive), len(reserved)])
    sections.append(
        "## 9. Code lists embedded in the extract metadata (cut B)\n\n"
        "Variables without an entry (id_, wtssnrps) are continuous and carry no code list.\n\n"
        + md_table(["variable", "substantive codes", "reserved codes"], rows)
    )

    Path(args.out).write_text("\n\n".join(sections) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
